"""
CloudGuard — Google Gemini AI Provider

Integrates with Google Gemini API via REST using httpx (no external SDK required).
Supports declarative tool calling and structured investigation/recommendations.
Enforces client timeouts, strips sensitive headers/keys from exceptions,
and fails safely with explicit error categories.
NEVER executes tools or mutates cloud/database state directly.
"""
from __future__ import annotations

import json
from typing import Any, Dict, List, Optional

import httpx

from core.providers.ai.base import (
    AIProvider,
    AIProviderError,
    AIProviderRawResponse,
    AIToolRequest,
)
from core.utils.logging import get_logger

log = get_logger(__name__)

GEMINI_API_BASE = "https://generativelanguage.googleapis.com/v1beta/models"


class GeminiAIProvider(AIProvider):
    """
    Real AI Provider using Google Gemini REST API.
    """

    def __init__(
        self,
        api_key: Optional[str] = None,
        model: str = "gemini-3.8-flash",
        timeout_seconds: float = 20.0,
    ) -> None:
        if not api_key or not api_key.strip():
            raise ValueError("GEMINI_API_KEY is not configured or empty.")

        self._api_key = api_key.strip()
        self._model = model.strip() or "gemini-3.8-flash"
        self._timeout_seconds = timeout_seconds

    @property
    def provider_type(self) -> str:
        return "gemini"

    @property
    def model_name(self) -> str:
        return self._model

    def generate_response(
        self,
        system_prompt: str,
        messages: List[Dict[str, Any]],
        available_tools: List[Dict[str, Any]],
    ) -> AIProviderRawResponse:
        """
        Produce declarative tool requests or structured recommendation via Gemini API.
        Never executes any tool directly.
        """
        url = f"{GEMINI_API_BASE}/{self._model}:generateContent?key={self._api_key}"

        # Convert conversation messages to Gemini contents format
        contents = []
        for msg in messages:
            role = msg.get("role", "user")
            content = msg.get("content", "")
            gemini_role = "model" if role in ("assistant", "system") else "user"

            if isinstance(content, str):
                contents.append({
                    "role": gemini_role,
                    "parts": [{"text": content}],
                })
            elif isinstance(content, list):
                text_parts = [
                    {"text": item.get("text", "")}
                    for item in content
                    if isinstance(item, dict) and "text" in item
                ]
                if text_parts:
                    contents.append({"role": gemini_role, "parts": text_parts})

        payload: Dict[str, Any] = {
            "contents": contents or [{"role": "user", "parts": [{"text": "Analyze findings."}]}],
            "generationConfig": {
                "temperature": 0.2,
                "maxOutputTokens": 2048,
            },
        }

        if system_prompt:
            payload["systemInstruction"] = {
                "parts": [{"text": system_prompt}]
            }

        try:
            with httpx.Client(timeout=self._timeout_seconds) as client:
                res = client.post(url, json=payload, headers={"Content-Type": "application/json"})

            if res.status_code == 400:
                err_data = res.json().get("error", {})
                raise AIProviderError(
                    f"Gemini Bad Request: {err_data.get('message', 'Invalid request')}",
                    error_category="validation_error",
                )
            elif res.status_code in (401, 403):
                raise AIProviderError(
                    "Invalid or unauthorized Gemini API key.",
                    error_category="authentication_error",
                )
            elif res.status_code == 429:
                raise AIProviderError(
                    "Gemini rate limit exceeded. Please wait before retrying.",
                    error_category="rate_limit",
                )
            elif res.status_code >= 500:
                raise AIProviderError(
                    f"Gemini server error ({res.status_code})",
                    error_category="upstream_error",
                )

            data = res.json()
            candidates = data.get("candidates", [])
            if not candidates:
                return AIProviderRawResponse(raw_text="No response generated by Gemini.")

            candidate = candidates[0]
            parts = candidate.get("content", {}).get("parts", [])
            reply_text = "".join(p.get("text", "") for p in parts)

            # Attempt parsing recommendation if formatted as JSON
            recommendation = None
            if "{" in reply_text and "}" in reply_text:
                try:
                    start = reply_text.index("{")
                    end = reply_text.rindex("}") + 1
                    json_str = reply_text[start:end]
                    parsed = json.loads(json_str)
                    if isinstance(parsed, dict) and "recommendation" in parsed:
                        recommendation = parsed.get("recommendation")
                    elif isinstance(parsed, dict) and "strategy" in parsed:
                        recommendation = parsed
                except Exception:
                    pass

            return AIProviderRawResponse(
                raw_text=reply_text,
                recommendation=recommendation,
            )

        except httpx.TimeoutException:
            log.warning("gemini_timeout", model=self._model)
            raise AIProviderError("Gemini request timed out.", error_category="timeout")
        except AIProviderError:
            raise
        except Exception as exc:
            log.error("gemini_call_failed", error=str(exc))
            raise AIProviderError(f"Gemini invocation failed: {str(exc)}", error_category="provider_error")
